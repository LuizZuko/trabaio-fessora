/* =====================================================================
   DATA WAREHOUSE CAMPO REAL ENERGIA - DDL STAR SCHEMA (PostgreSQL)
   ===================================================================== */

DROP SCHEMA IF EXISTS dw_campo_real CASCADE;
CREATE SCHEMA dw_campo_real;

-- 1. DIMENSÕES
CREATE TABLE dw_campo_real.dim_submercado (
    sk_submercado   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_submercado  VARCHAR(10) NOT NULL,
    nome_submercado VARCHAR(40) NOT NULL,
    regioes         VARCHAR(80) NOT NULL
);

CREATE TABLE dw_campo_real.dim_fonte (
    sk_fonte     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_fonte    VARCHAR(10) NOT NULL,
    descricao    VARCHAR(40) NOT NULL,
    renovavel    BOOLEAN NOT NULL,
    intermitente BOOLEAN NOT NULL
);

CREATE TABLE dw_campo_real.dim_usina (
    sk_usina             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usina            VARCHAR(12) NOT NULL,
    nome_usina           VARCHAR(80) NOT NULL,
    cod_fonte            VARCHAR(10) NOT NULL,
    cod_submercado       VARCHAR(10) NOT NULL,
    uf                   CHAR(2) NOT NULL,
    municipio            VARCHAR(60) NOT NULL,
    latitude             NUMERIC(9,6) NOT NULL,
    longitude            NUMERIC(9,6) NOT NULL,
    potencia_mw          NUMERIC(8,2) NOT NULL,
    data_inicio_operacao DATE NOT NULL,
    situacao             VARCHAR(20) NOT NULL,
    data_inicio_scd      DATE NOT NULL DEFAULT '1900-01-01',
    data_fim_scd         DATE DEFAULT '9999-12-31',
    atual_scd            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dw_campo_real.dim_tempo (
    sk_tempo         INT PRIMARY KEY,
    data_hora        TIMESTAMP NOT NULL UNIQUE,
    data             DATE NOT NULL,
    ano              INT NOT NULL,
    mes              INT NOT NULL,
    nome_mes         VARCHAR(15) NOT NULL,
    dia              INT NOT NULL,
    hora             INT NOT NULL,
    dia_semana       VARCHAR(15) NOT NULL,
    e_final_semana   BOOLEAN NOT NULL,
    e_feriado        BOOLEAN NOT NULL,
    estacao_ano      VARCHAR(15) NOT NULL,
    patamar_carga    VARCHAR(15) NOT NULL
);

