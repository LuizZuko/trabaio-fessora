-- 2. TABELAS FATO
CREATE TABLE dw_campo_real.fato_geracao (
    sk_tempo              INT NOT NULL REFERENCES dw_campo_real.dim_tempo (sk_tempo),
    sk_usina              INT NOT NULL REFERENCES dw_campo_real.dim_usina (sk_usina),
    sk_submercado         INT NOT NULL REFERENCES dw_campo_real.dim_submercado (sk_submercado),
    sk_fonte              INT NOT NULL REFERENCES dw_campo_real.dim_fonte (sk_fonte),
    energia_gerada_mwh    NUMERIC(12,3) NOT NULL,
    disponibilidade_mw    NUMERIC(8,2) NOT NULL,
    fator_capacidade_pct  NUMERIC(5,2) NOT NULL,
    pld_aplicado_rs_mwh   NUMERIC(10,2) NOT NULL,
    receita_valorada_rs   NUMERIC(14,2) NOT NULL,
    flag_parada           BOOLEAN NOT NULL DEFAULT FALSE,
    tipo_parada           VARCHAR(20) DEFAULT 'Nenhuma',
    energia_perdida_mwh   NUMERIC(12,3) DEFAULT 0.000,
    receita_perdida_rs    NUMERIC(14,2) DEFAULT 0.00,
    PRIMARY KEY (sk_tempo, sk_usina)
);

CREATE TABLE dw_campo_real.fato_pld (
    sk_tempo       INT NOT NULL REFERENCES dw_campo_real.dim_tempo (sk_tempo),
    sk_submercado  INT NOT NULL REFERENCES dw_campo_real.dim_submercado (sk_submercado),
    pld_rs_mwh     NUMERIC(10,2) NOT NULL,
    origem_dado    VARCHAR(30) NOT NULL,
    PRIMARY KEY (sk_tempo, sk_submercado)
);

CREATE TABLE dw_campo_real.fato_clima (
    sk_tempo              INT NOT NULL REFERENCES dw_campo_real.dim_tempo (sk_tempo),
    sk_usina              INT NOT NULL REFERENCES dw_campo_real.dim_usina (sk_usina),
    temperatura_2m        NUMERIC(5,2),
    chuva_mm              NUMERIC(6,2),
    vento_velocidade_10m  NUMERIC(5,2),
    radiacao_solar_w_m2   NUMERIC(7,2),
    PRIMARY KEY (sk_tempo, sk_usina)
);