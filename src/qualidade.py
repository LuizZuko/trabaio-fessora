import sys
import os
import pandas as pd
import numpy as np
from sqlalchemy import create_engine, text

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from config import Config

def obter_engine():
    return create_engine(Config.get_db_connection_string())

def preparar_tabela_metricas(engine):
    sql = text("""
        CREATE TABLE IF NOT EXISTS metrica_qualidade (
            id_metrica INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            regra VARCHAR(100) NOT NULL,
            dimensao VARCHAR(40) NOT NULL,
            tabela VARCHAR(50) NOT NULL,
            registros_avaliados INT NOT NULL,
            registros_falha INT NOT NULL,
            percentual_falha NUMERIC(5,2) NOT NULL,
            executado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
    """)
    with engine.begin() as conn:
        conn.execute(sql)

def salvar_metrica(engine, regra, dimensao, tabela, total, falhas):
    # Conversão explícita para int e float nativos do Python (evita erro de numpy.int64 no psycopg2)
    total_int = int(total)
    falhas_int = int(falhas)
    pct_float = float(round((falhas_int / total_int * 100), 2)) if total_int > 0 else 0.0
    
    sql = text("""
        INSERT INTO metrica_qualidade (regra, dimensao, tabela, registros_avaliados, registros_falha, percentual_falha)
        VALUES (:regra, :dimensao, :tabela, :total, :falhas, :pct);
    """)
    with engine.begin() as conn:
        conn.execute(sql, {
            "regra": str(regra),
            "dimensao": str(dimensao),
            "tabela": str(tabela),
            "total": total_int,
            "falhas": falhas_int,
            "pct": pct_float
        })
    print(f"[{dimensao}] {tabela} - {regra}: {falhas_int}/{total_int} falhas ({pct_float}%)")

# =====================================================================
# FUNÇÕES REUTILIZÁVEIS DE QUALIDADE (7 DIMENSÕES)
# =====================================================================

# 1. COMPLETUDE
def checar_completude(df, tabela, coluna, engine):
    total = len(df)
    falhas = df[coluna].isna().sum()
    salvar_metrica(engine, f"Campo {coluna} não nulo", "Completude", tabela, total, falhas)

# 2. UNICIDADE
def checar_unicidade(df, tabela, colunas_chave, engine):
    total = len(df)
    falhas = df.duplicated(subset=colunas_chave, keep=False).sum()
    salvar_metrica(engine, f"Chave única {colunas_chave}", "Unicidade", tabela, total, falhas)

# 3. VALIDADE
def checar_validade_faixa(df, tabela, coluna, min_val, max_val, engine):
    total = len(df)
    falhas = df[~df[coluna].between(min_val, max_val, inclusive="both") & df[coluna].notna()].shape[0]
    salvar_metrica(engine, f"Valor de {coluna} entre {min_val} e {max_val}", "Validade", tabela, total, falhas)

# 4. CONSISTÊNCIA
def checar_consistencia_datas_parada(df, tabela, engine):
    total = len(df)
    falhas = df[df["fim"] <= df["inicio"]].shape[0]
    salvar_metrica(engine, "Data fim da parada maior que inicio", "Consistência", tabela, total, falhas)

# 5. ACURÁCIA
def checar_acuracia_geracao(df_medicao, df_usina, engine):
    total = len(df_medicao)
    df_merged = df_medicao.merge(df_usina, on="id_usina", how="inner")
    falhas = df_merged[df_merged["energia_mwh"] > df_merged["potencia_mw"]].shape[0]
    salvar_metrica(engine, "Energia gerada menor ou igual a Potência Instalada", "Acurácia", "medicao_geracao", total, falhas)

# 6. INTEGRIDADE REFERENCIAL
def checar_integridade_referencial(df_fato, df_dim, tabela_fato, col_fk, col_pk, engine):
    total = len(df_fato)
    ids_validos = set(df_dim[col_pk].dropna().unique())
    falhas = df_fato[~df_fato[col_fk].isin(ids_validos)].shape[0]
    salvar_metrica(engine, f"Chave {col_fk} existe na dimensão", "Integridade Referencial", tabela_fato, total, falhas)

# 7. ATUALIDADE
def checar_atualidade(df, tabela, col_data_recebido, col_data_evento, max_horas_atraso, engine):
    total = len(df)
    atraso_horas = (df[col_data_recebido] - df[col_data_evento]).dt.total_seconds() / 3600
    falhas = df[(atraso_horas > max_horas_atraso) | (atraso_horas < 0)].shape[0]
    salvar_metrica(engine, f"Dado recebido em até {max_horas_atraso}h sem datas futuras", "Atualidade", tabela, total, falhas)

# =====================================================================
# PIPELINE DE AUDITORIA DE QUALIDADE
# =====================================================================
def executar_auditoria():
    engine = obter_engine()
    preparar_tabela_metricas(engine)
    
    print("\n==============================================")
    print(" INICIANDO AUDITORIA DE QUALIDADE DE DADOS ")
    print("==============================================")
    
    with engine.connect() as conn:
        df_usina = pd.read_sql("SELECT * FROM usina;", conn)
        df_medicao = pd.read_sql("SELECT * FROM medicao_geracao;", conn)
        df_parada = pd.read_sql("SELECT * FROM parada_usina;", conn)
        df_pld = pd.read_sql("SELECT * FROM pld_horario;", conn)

    # Execução das 7 dimensões
    checar_completude(df_medicao, "medicao_geracao", "energia_mwh", engine)
    checar_completude(df_medicao, "medicao_geracao", "id_usina", engine)
    checar_unicidade(df_usina, "usina", ["cod_usina"], engine)
    checar_unicidade(df_medicao, "medicao_geracao", ["id_usina", "data_hora"], engine)
    checar_validade_faixa(df_usina, "usina", "latitude", -34.0, 5.0, engine)
    checar_validade_faixa(df_pld, "pld_horario", "pld_rs_mwh", 50.0, 1500.0, engine)
    checar_consistencia_datas_parada(df_parada, "parada_usina", engine)
    checar_acuracia_geracao(df_medicao, df_usina, engine)
    checar_integridade_referencial(df_medicao, df_usina, "medicao_geracao", "id_usina", "id_usina", engine)
    checar_atualidade(df_medicao, "medicao_geracao", "recebido_em", "data_hora", 48, engine)
    
    print("\nAuditoria concluída com sucesso! Métricas gravadas na tabela metrica_qualidade.\n")

if __name__ == "__main__":
    executar_auditoria()